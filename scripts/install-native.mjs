import { mkdir, readFile, writeFile, chmod } from 'node:fs/promises';
import { homedir, platform } from 'node:os';
import { join, dirname } from 'node:path';
import { ROOT, extensionIdentity, requireModernNode } from './project.mjs';
import { HOST_NAME } from '../extension/lib/contracts.js';
requireModernNode();
if (!['darwin', 'linux'].includes(platform())) throw new Error('首版安装脚本支持 macOS / Linux；Windows 注册流程尚未实现。');
const nativeRoot = platform() === 'darwin' ? join(homedir(), 'Library/Application Support/Google/Chrome/NativeMessagingHosts') : join(homedir(), '.config/google-chrome/NativeMessagingHosts');
const ownRoot = join(homedir(), '.nexly-web-agent');
const manifestPath = join(nativeRoot, `${HOST_NAME}.json`);
const launcher = join(ownRoot, 'native-host.sh');
const { id } = await extensionIdentity();
const quote = (value) => `'${value.replace(/'/g, "'\\''")}'`;
const script = `#!/bin/sh\n# Generated by Nexly. No API keys or provider settings are copied here.\nexec ${quote(process.execPath)} ${quote(join(ROOT, 'bridge/native-host.mjs'))} "$@"\n`;
const manifest = { name: HOST_NAME, description: 'Nexly local CLI bridge', path: launcher, type: 'stdio', allowed_origins: [`chrome-extension://${id}/`] };
if (process.argv.includes('--dry-run')) {
  console.log(JSON.stringify({ node: process.execPath, manifestPath, launcher, extensionId: id, manifest }, null, 2));
} else {
  let existing;
  try { existing = JSON.parse(await readFile(manifestPath, 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw new Error('已有同名 native host 配置无法读取，未覆盖'); }
  if (existing && (existing.path !== launcher || existing.allowed_origins?.[0] !== manifest.allowed_origins[0])) throw new Error('已有不同来源的同名 native host，未覆盖。请先核对并卸载旧配置。');
  await mkdir(ownRoot, { recursive: true, mode: 0o700 });
  await mkdir(nativeRoot, { recursive: true });
  await writeFile(launcher, script, { mode: 0o700 }); await chmod(launcher, 0o700);
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n', { mode: 0o600 });
  await writeFile(join(ownRoot, 'installation.json'), JSON.stringify({ projectRoot: ROOT, manifestPath, launcher, extensionId: id }, null, 2), { mode: 0o600 });
  console.log(`本地桥安装完成。\n扩展 ID：${id}\nChrome 配置：${manifestPath}\nNode：${process.execPath}\n未修改 ccSwitch、CLI 账号或默认 Node。`);
}
