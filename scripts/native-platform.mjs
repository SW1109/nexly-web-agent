import { homedir, platform } from 'node:os';
import { posix, win32 } from 'node:path';
import { HOST_NAME } from '../extension/lib/contracts.js';

export function nativeInstallationPaths({ system = platform(), home = homedir(), browser = 'chrome' } = {}) {
  if (!['win32', 'darwin', 'linux'].includes(system)) throw new Error('安装脚本支持 Windows、macOS 和 Linux。');
  if (!['chrome', 'edge'].includes(browser)) throw new Error('浏览器仅支持 chrome 或 edge。');
  const path = system === 'win32' ? win32 : posix;
  const ownRoot = path.join(home, '.nexly-web-agent');
  const nativeRoot = system === 'win32' ? (browser === 'edge' ? path.join(ownRoot, 'edge') : ownRoot) : system === 'darwin'
    ? path.join(home, `Library/Application Support/${browser === 'edge' ? 'Microsoft Edge' : 'Google/Chrome'}/NativeMessagingHosts`)
    : path.join(home, `.config/${browser === 'edge' ? 'microsoft-edge' : 'google-chrome'}/NativeMessagingHosts`);
  return {
    ownRoot, nativeRoot, browser,
    installationPath: path.join(ownRoot, browser === 'edge' ? 'installation-edge.json' : 'installation.json'),
    manifestPath: path.join(nativeRoot, `${HOST_NAME}.json`),
    launcher: path.join(ownRoot, `native-host${browser === 'edge' ? '-edge' : ''}.${system === 'win32' ? 'cmd' : 'sh'}`),
    registryKey: system === 'win32' ? `HKCU\\${nativeRegistrySubkey(browser)}` : null
  };
}

export function nativeLauncher(nodePath, hostPath, system = platform()) {
  if (system === 'win32') {
    const quote = (value) => {
      if (/["\r\n]/.test(value)) throw new Error('Windows 本地桥路径包含无效字符。');
      return `"${value.replace(/%/g, '%%')}"`;
    };
    return `@echo off\r\nsetlocal DisableDelayedExpansion\r\nchcp 65001 >nul 2>nul\r\n${quote(nodePath)} ${quote(hostPath)} %*\r\n`;
  }
  const quote = (value) => `'${value.replace(/'/g, "'\\''")}'`;
  return `#!/bin/sh\n# Generated by QuizMate. No API keys or provider settings are copied here.\nexec ${quote(nodePath)} ${quote(hostPath)} "$@"\n`;
}

export function nativeRegistrySubkey(browser = 'chrome') {
  if (!['chrome', 'edge'].includes(browser)) throw new Error('浏览器仅支持 chrome 或 edge。');
  return `Software\\${browser === 'edge' ? 'Microsoft\\Edge' : 'Google\\Chrome'}\\NativeMessagingHosts\\${HOST_NAME}`;
}
// 只有明确提供的商店 ID 才能获得本地桥权限，绝不使用通配来源。
export function nativeOptions(args, defaultId) {
  let browser = 'chrome', extensionId = defaultId, dryRun = false;
  const seen = new Set();
  for (let index = 0; index < args.length; index++) {
    const option = args[index];
    if (seen.has(option)) throw new Error(`参数重复：${option}`);
    seen.add(option);
    if (option === '--dry-run') { dryRun = true; continue; }
    if (!['--browser', '--extension-id'].includes(option)) throw new Error(`未知参数：${option}`);
    const value = args[++index];
    if (!value || value.startsWith('--')) throw new Error(`${option} 缺少值`);
    if (option === '--browser') browser = value; else extensionId = value;
  }
  nativeRegistrySubkey(browser);
  if (!/^[a-p]{32}$/.test(extensionId)) throw new Error('扩展 ID 必须为 32 位 a-p 字母，请从浏览器扩展管理页复制');
  return { browser, extensionId, dryRun };
}
