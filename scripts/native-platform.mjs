import { homedir, platform } from 'node:os';
import { posix, win32 } from 'node:path';
import { HOST_NAME } from '../extension/lib/contracts.js';

export function nativeInstallationPaths({ system = platform(), home = homedir() } = {}) {
  if (!['win32', 'darwin', 'linux'].includes(system)) throw new Error('安装脚本支持 Windows、macOS 和 Linux。');
  const path = system === 'win32' ? win32 : posix;
  const ownRoot = path.join(home, '.nexly-web-agent');
  const nativeRoot = system === 'win32' ? ownRoot : system === 'darwin'
    ? path.join(home, 'Library/Application Support/Google/Chrome/NativeMessagingHosts')
    : path.join(home, '.config/google-chrome/NativeMessagingHosts');
  return {
    ownRoot, nativeRoot,
    manifestPath: path.join(nativeRoot, `${HOST_NAME}.json`),
    launcher: path.join(ownRoot, system === 'win32' ? 'native-host.cmd' : 'native-host.sh'),
    registryKey: system === 'win32' ? `HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts\\${HOST_NAME}` : null
  };
}

export function nativeLauncher(nodePath, hostPath, system = platform()) {
  if (system === 'win32') {
    const quote = (value) => {
      if (/["\r\n]/.test(value)) throw new Error('Windows 本地桥路径包含无效字符。');
      return `"${value.replace(/%/g, '%%')}"`;
    };
    return `@echo off\r\nsetlocal DisableDelayedExpansion\r\nchcp 65001 >nul 2>nul\r\n${quote(nodePath)} ${quote(hostPath)} %*\r\n`;
  }
  const quote = (value) => `'${value.replace(/'/g, "'\\''")}'`;
  return `#!/bin/sh\n# Generated by Nexly. No API keys or provider settings are copied here.\nexec ${quote(nodePath)} ${quote(hostPath)} "$@"\n`;
}
